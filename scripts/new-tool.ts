import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// Kept in sync with BUILT_IN_PAGES and customPages; src/modules/modules.test.ts is the backstop.
export const RESERVED = ['overview', 'activity', 'about', 'investigation', 'vendors'];

export function validateArgs(id = '', title = '') {
  if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(id) || id.length > 32)
    throw new Error('Tool id must be a lowercase slug like "vendor-requests" (max 32 chars).');
  if (RESERVED.includes(id)) throw new Error(`"${id}" is already used by a built-in page.`);
  if (!/^[A-Za-z0-9][A-Za-z0-9 &,/-]{0,39}$/.test(title))
    throw new Error('Title must be 1-40 letters, numbers, spaces or & , / - characters.');
}

export const identifier = (id: string) =>
  id.replace(/-([a-z0-9])/g, (_, char: string) => char.toUpperCase());

export function renderTool(id: string, title: string) {
  const name = identifier(id);
  const prefix = id
    .split('-')
    .map((part) => part[0])
    .join('')
    .toUpperCase()
    .slice(0, 4);
  const index = `import type { ToolModule } from '../../core/types';
import { samples } from './samples';

// Generated by \`npm run new-tool\`. Edit statuses, fields, details, actions and metrics to fit the workflow.
export const ${name}: ToolModule = {
  id: '${id}',
  title: '${title}',
  shortTitle: '${title}',
  icon: 'box',
  color: 'purple',
  description: 'Review synthetic ${title.toLowerCase()}. Changes stay in this browser.',
  recordLabel: 'requests',
  primaryColumn: 'Request',
  secondaryColumn: 'Category',
  secondaryValue: (r) => String(r.fields.category),
  statuses: { Pending: 'amber', Approved: 'green', Rejected: 'neutral' },
  owners: ['Unassigned', 'You', 'Alex Morgan', 'Jamie Brooks'],
  isOpen: (r) => r.status === 'Pending',
  noActionMessage: () => 'Resolved in the local demo. You can still assign it or add a note.',
  details: [
    { label: 'Category', value: (r) => String(r.fields.category) },
    { label: 'Summary', value: (r) => String(r.fields.summary) },
  ],
  notice: 'Synthetic local demo data. No external system is connected.',
  actions: [
    {
      id: 'approve',
      label: 'Approve request',
      tone: 'primary',
      confirmation: 'Approve this request in local demo data only.',
      available: (r) => r.status === 'Pending',
      apply: (r) => ({ ...r, status: 'Approved' }),
    },
    {
      id: 'reject',
      label: 'Reject request',
      tone: 'danger',
      confirmation: 'Reject this request in local demo data only.',
      available: (r) => r.status === 'Pending',
      apply: (r) => ({ ...r, status: 'Rejected' }),
    },
  ],
  metrics: (records) => [
    { label: 'Sample requests', value: String(records.length), hint: 'Synthetic examples' },
    {
      label: 'Pending',
      value: String(records.filter((r) => r.status === 'Pending').length),
      hint: 'Awaiting a decision',
    },
    {
      label: 'Approved',
      value: String(records.filter((r) => r.status === 'Approved').length),
      hint: 'Local decisions only',
    },
  ],
  validateFields: (r) => ['category', 'summary'].every((key) => typeof r.fields[key] === 'string'),
  samples,
};
`;
  const rows: [string, string, string, string, number, string][] = [
    ['Northwind Supplies', 'Software', 'Pending', 'Unassigned', 2, 'Annual license renewal.'],
    ['Contoso Analytics', 'Services', 'Pending', 'You', 6, 'New data-analysis contract.'],
    ['Fabrikam Logistics', 'Hardware', 'Approved', 'Alex Morgan', 30, 'Replacement scanners.'],
    ['Tailspin Travel', 'Travel', 'Rejected', 'Jamie Brooks', 72, 'Duplicate of an approved trip.'],
  ];
  const samples = `import type { ToolRecord } from '../../core/types';

// Fictional sample records relative to \`now\`; used on first load and reset.
export function samples(now: Date): ToolRecord[] {
  const time = (hours: number) => new Date(now.getTime() - hours * 3_600_000).toISOString();
  return [
${rows
  .map(
    ([vendor, category, status, owner, hours, summary], i) => `    {
      id: '${prefix}-${String(i + 1).padStart(3, '0')}',
      name: '${vendor}',
      subtitle: '${category} request',
      status: '${status}',
      owner: '${owner}',
      openedAt: time(${hours + 24}),
      updatedAt: time(${hours}),
      version: 1,
      fields: { category: '${category}', summary: '${summary}' },
    },`,
  )
  .join('\n')}
  ];
}
`;
  return { index, samples };
}

export function addToRegistry(source: string, id: string) {
  const name = identifier(id);
  const list = /(export const modules: ToolModule\[\] = \[)([^\]]*)(\];)/;
  const imports = [...source.matchAll(/^import \{ \w+ \} from '\.\/[\w-]+';$/gm)];
  if (!list.test(source) || !imports.length)
    throw new Error('src/modules/index.ts no longer matches the expected registry shape.');
  if (source.includes(`from './${id}'`)) throw new Error(`"${id}" is already registered.`);
  const last = imports[imports.length - 1];
  const at = last.index! + last[0].length;
  const withImport = `${source.slice(0, at)}\nimport { ${name} } from './${id}';${source.slice(at)}`;
  return withImport.replace(
    list,
    (_, open: string, items: string, close: string) =>
      `${open}${items.trim().replace(/,$/, '')}, ${name}${close}`,
  );
}

export function createTool(root: string, id: string, title: string) {
  validateArgs(id, title);
  const dir = join(root, 'src/modules', id);
  const registry = join(root, 'src/modules/index.ts');
  if (existsSync(dir)) throw new Error(`src/modules/${id} already exists.`);
  const updated = addToRegistry(readFileSync(registry, 'utf8'), id);
  const { index, samples } = renderTool(id, title);
  mkdirSync(dir);
  writeFileSync(join(dir, 'index.ts'), index);
  writeFileSync(join(dir, 'samples.ts'), samples);
  writeFileSync(registry, updated);
  return [join(dir, 'index.ts'), join(dir, 'samples.ts'), registry];
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [id, title] = process.argv.slice(2);
  try {
    const files = createTool(process.cwd(), id, title);
    const format = spawnSync('npx', ['prettier', '--write', ...files], { encoding: 'utf8' });
    if (format.status !== 0) {
      console.error(`Created the files, but Prettier failed:\n${format.stderr || format.error}`);
      console.error('Fix the error, then run: npx prettier --write ' + files.join(' '));
      process.exit(1);
    }
    console.log(`Created ${title} (#${id}):\n${files.map((file) => `  ${file}`).join('\n')}`);
    console.log('\nNext: npm test (checks the new tool automatically), then npm run dev.');
  } catch (error) {
    console.error((error as Error).message);
    console.error('Usage: npm run new-tool -- <id> "<Title>"');
    process.exit(1);
  }
}
